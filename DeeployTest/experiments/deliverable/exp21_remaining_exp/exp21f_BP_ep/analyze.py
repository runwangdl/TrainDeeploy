"""exp21f analysis: tables (results/summary.md, summary.csv, summary.json) + plot (results/exp21f_bp_epochs.png)."""
import csv, glob, json, os
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")
SUBJ = ("S01", "S02", "S03", "S04")
ROUNDS = ("1", "2", "3", "4")
TOL = 0.5                                     # plateau band, pp
STEPS_PER_EPOCH = 54 / 4                      # 13.5 update steps per epoch at 30 % / n_accum 4
EXP21D = os.path.join(HERE, "..", "exp21d_70%data", "results", "bp")

recs = {}
for f in glob.glob(os.path.join(RES, "seed*", "e*", "S0*.json")):
    r = json.load(open(f)); recs[(r["seed"], r["epochs"], r["subject"])] = r
seeds = sorted({k[0] for k in recs})
grid = sorted({k[1] for k in recs if k[0] == 42})
seeds = [sd for sd in seeds if all((sd, e, s) in recs for e in grid for s in ("S01", "S02", "S03", "S04"))]


def complete(seed, e):
    return all((seed, e, s) in recs for s in SUBJ)


def mean4(seed, e, key="mean_val_next"):
    return float(np.mean([recs[(seed, e, s)][key] for s in SUBJ]))


L = ["# exp21f results (auto-generated by analyze.py)", ""]
# --- consistency check vs exp21d
L += ["## Consistency check vs exp21d (same code path, same settings)", "",
      "| epochs | subject | exp21f r1..r4 val_next | exp21d | max abs diff |", "|---|---|---|---|---:|"]
for e, arm in ((40, "p30_e40"), (120, "p30_e120")):
    for s in SUBJ:
        f = os.path.join(EXP21D, arm, f"{s}.json")
        if (42, e, s) in recs and os.path.exists(f):
            a = [recs[(42, e, s)]["per_round"][r]["val_next"] for r in ROUNDS]
            b = [json.load(open(f))["per_round"][r]["val_next"] for r in ROUNDS]
            L.append(f"| {e} | {s} | {', '.join(f'{x:.2f}' for x in a)} | {', '.join(f'{x:.2f}' for x in b)} | "
                     f"{max(abs(x - y) for x, y in zip(a, b)):.2f} |")
L.append("")

# --- main table seed 42
rows = []
L += ["## Seed 42 (deployed draw): mean val_next over rounds 1-4, per subject", "",
      "| epochs | steps/round | S01 | S02 | S03 | S04 | **mean val_next** | mean val_in | mean train | Δ vs 40 ep |",
      "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
ref40 = mean4(42, 40) if complete(42, 40) else None
for e in grid:
    if not complete(42, e):
        continue
    st = recs[(42, e, "S01")]["update_steps_per_round"][0]
    m, vi, tr = mean4(42, e), mean4(42, e, "mean_val_in"), mean4(42, e, "mean_train")
    per = [recs[(42, e, s)]["mean_val_next"] for s in SUBJ]
    rows.append({"seed": 42, "epochs": e, "steps_per_round": st, **dict(zip(SUBJ, per)),
                 "mean_val_next": m, "mean_val_in": vi, "mean_train": tr})
    d = f"{m - ref40:+.2f}" if ref40 is not None else ""
    L.append(f"| {e} | {st} | " + " | ".join(f"{x:.2f}" for x in per) +
             f" | **{m:.2f}** | {vi:.2f} | {tr:.2f} | {d} |")
L.append("")

# --- per round table
L += ["## Seed 42 per round (val_next = accuracy on batch r+1)", "",
      "| epochs | subject | r1 | r2 | r3 | r4 | mean | val_in r1..r4 |", "|---:|---|---:|---:|---:|---:|---:|---|"]
for e in grid:
    for s in SUBJ:
        if (42, e, s) in recs:
            p = recs[(42, e, s)]["per_round"]
            L.append(f"| {e} | {s} | " + " | ".join(f"{p[r]['val_next']:.2f}" for r in ROUNDS) +
                     f" | {recs[(42, e, s)]['mean_val_next']:.2f} | " +
                     ", ".join(f"{p[r]['val_in']:.1f}" for r in ROUNDS) + " |")
L.append("")

# --- seeds
full = [e for e in grid if all(complete(sd, e) for sd in seeds)]
if len(seeds) > 1:
    L += [f"## Draw-seed robustness: 4-subject mean val_next per seed (seeds {seeds})", "",
          "| epochs | " + " | ".join(f"seed {sd}" for sd in seeds) + " | **mean over seeds** | seed range |",
          "|---:|" + "---:|" * (len(seeds) + 2)]
    for e in full:
        v = [mean4(sd, e) for sd in seeds]
        for sd in seeds:
            if sd != 42:
                rows.append({"seed": sd, "epochs": e, "steps_per_round": int(e * STEPS_PER_EPOCH),
                             **{s: recs[(sd, e, s)]["mean_val_next"] for s in SUBJ},
                             "mean_val_next": mean4(sd, e), "mean_val_in": mean4(sd, e, "mean_val_in"),
                             "mean_train": mean4(sd, e, "mean_train")})
        L.append(f"| {e} | " + " | ".join(f"{x:.2f}" for x in v) + f" | **{np.mean(v):.2f}** | {max(v) - min(v):.2f} |")
    L.append("")


def plateau(curve):
    es, ms = zip(*curve)
    pk = int(np.argmax(ms))
    band = [e for e, m in curve if m >= ms[pk] - TOL]
    return es[pk], ms[pk], band


summary = {"grid": grid, "seeds": seeds, "tol_pp": TOL}
c42 = [(e, mean4(42, e)) for e in grid if complete(42, e)]
if c42:
    pe, pm, band = plateau(c42)
    summary["seed42"] = {"peak_epochs": pe, "peak_mean": pm, "within_tol": band, "e40": ref40}
    L += ["## Plateau", "", f"* seed 42: peak **{pm:.2f} % at {pe} epochs**; epochs within {TOL} pp of peak: {band}; "
          f"40 ep = {ref40:.2f} ({ref40 - pm:+.2f} pp vs peak)"]
if len(seeds) > 1 and full:
    cm = [(e, float(np.mean([mean4(sd, e) for sd in seeds]))) for e in full]
    pe, pm, band = plateau(cm)
    m40 = dict(cm).get(40)
    summary["seed_mean"] = {"peak_epochs": pe, "peak_mean": pm, "within_tol": band, "e40": m40}
    L.append(f"* mean over seeds {seeds}: peak **{pm:.2f} % at {pe} epochs**; within {TOL} pp: {band}; "
             f"40 ep = {m40:.2f} ({m40 - pm:+.2f} pp vs peak)")
L.append("")
open(os.path.join(RES, "summary.md"), "w").write("\n".join(L) + "\n")
json.dump({**summary, "rows": rows}, open(os.path.join(RES, "summary.json"), "w"), indent=1)
with open(os.path.join(RES, "summary.csv"), "w", newline="") as h:
    w = csv.DictWriter(h, fieldnames=list(rows[0].keys())); w.writeheader(); w.writerows(rows)
print("\n".join(L))

# --- plot
COL = {"S01": "#2a78d6", "S02": "#eb6834", "S03": "#1baf7a", "S04": "#eda100"}
INK, MUTED = "#0b0b0b", "#52514e"
ncol = 2 if (len(seeds) > 1 and full) else 1
fig, axes = plt.subplots(1, ncol, figsize=(7.2 * ncol, 6.0), squeeze=False)
ax = axes[0][0]
for s in SUBJ:
    es = [e for e in grid if (42, e, s) in recs]
    ax.plot(es, [recs[(42, e, s)]["mean_val_next"] for e in es], "-o", color=COL[s], lw=1.6, ms=4, label=s)
es, ms = zip(*c42)
ax.plot(es, ms, "-o", color=INK, lw=2.4, ms=5, label="mean (4 subj.)")
ax.set_title("Seed 42 (deployed draw): per subject + mean", fontsize=11)
panels = [(ax, c42, summary["seed42"])]
if ncol == 2:
    ax2 = axes[0][1]
    for sd, ls in zip(seeds, ("-", "--", ":")):
        cc = [(e, mean4(sd, e)) for e in grid if complete(sd, e)]
        ax2.plot(*zip(*cc), ls, color=MUTED, lw=1.2, marker="o", ms=3, label=f"seed {sd} (4-subj. mean)")
    ax2.plot(*zip(*cm), "-o", color=INK, lw=2.4, ms=5, label=f"mean over {len(seeds)} seeds")
    ax2.set_title(f"4-subject mean, {len(seeds)} labelled-draw seeds", fontsize=11)
    panels.append((ax2, cm, summary["seed_mean"]))
    zo = os.path.join(HERE, "..", "exp21d_70%data", "results", "zo", "p30_e120")
    if all(os.path.exists(os.path.join(zo, f"{s}.json")) for s in SUBJ):
        zm = float(np.mean([json.load(open(os.path.join(zo, f"{s}.json")))["mean_val_next"] for s in SUBJ]))
        ax2.axhline(zm, color="#1baf7a", lw=1.4, ls="-.", label=f"ZO fp32, 1620 steps, seed 42 (exp21d): {zm:.2f}")
for a, curve, sm in panels:
    a.axhspan(sm["peak_mean"] - TOL, sm["peak_mean"], color="#2a78d6", alpha=0.10, lw=0,
              label=f"plateau band (peak − {TOL} pp)")
    a.axvline(40, color="#e34948", lw=1.4, ls="--", label="40 ep = deployed BP (540 steps)")
    a.axvline(120, color="#6250d6", lw=1.4, ls=":", label="120 ep = ZO step count (1620 steps)")
    a.annotate(f"peak {sm['peak_mean']:.2f} @ {sm['peak_epochs']} ep", (sm["peak_epochs"], sm["peak_mean"]),
               xytext=(18, 28), textcoords="offset points", fontsize=9, color=INK,
               arrowprops=dict(arrowstyle="-", color=MUTED, lw=0.8))
    a.set_xlabel("epochs per round (every round)"); a.set_ylabel("balanced acc. on next batch, mean r1–r4 [%]")
    a.grid(alpha=0.25); a.spines[["top", "right"]].set_visible(False)
    top = a.secondary_xaxis("top", functions=(lambda x: x * STEPS_PER_EPOCH, lambda x: x / STEPS_PER_EPOCH))
    top.set_xlabel("update steps per round (×13.5)", color=MUTED)
    a.legend(fontsize=8, loc="upper center", bbox_to_anchor=(0.5, -0.13), ncol=3, frameon=False)
fig.suptitle("exp21f — BP epochs sweep, fold 3, vocalized, S01–S04 (separate chain per epoch count)", fontsize=12)
fig.tight_layout()
fig.savefig(os.path.join(RES, "exp21f_bp_epochs.png"), dpi=150)
