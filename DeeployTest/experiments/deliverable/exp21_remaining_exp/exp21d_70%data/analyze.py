"""exp21d -- collect results/<recipe>/<arm>/<subject>.json into tables + plot.

Writes results/summary.csv (one row per recipe/arm/subject/round), results/summary.md (tables) and
results/exp21d_70pct_equal_steps.png. Also checks every 30 % baseline against the older run of the
same setting (exp6/11/12/13 sweep.json epoch 120 for ZO/QZO/ECO; exp1 seed 42 for BP @ 40 epochs).
"""
import csv, json, os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(HERE, "results")
CLEANUP = "/Users/qiwenwu/ETH/SilentWear/SilentWear/PyTorch_for_On_Device/CleanUp"
SUBJ = ["S01", "S02", "S03", "S04"]
NAMES = {"bp": "BP", "zo": "ZO (fp32 MeZO)", "qzo": "QZO (int8 direct)", "eco": "QZO_ECO"}
ARM_INFO = {  # arm -> (data %, windows, epochs label)
    "p30_e40": ("30 %", 54, "40"), "p70_eq540": ("70 %", 126, "17.14 (cap 540)"),
    "p70_e40": ("70 %", 126, "40"),
    "p30_e120": ("30 %", 54, "120"), "p70_eq1620": ("70 %", 126, "51.43 (cap 1620)"),
    "p70_e120": ("70 %", 126, "120"),
}
# (recipe, budget) -> (baseline, equal-steps, more-steps)
COMPARISONS = [
    ("bp", "540 steps (BP deployed, 40 ep @30 %)", "p30_e40", "p70_eq540", "p70_e40"),
    ("bp", "1620 steps (ZO-recipe budget, 120 ep @30 %)", "p30_e120", "p70_eq1620", None),
    ("zo", "1620 steps (deployed)", "p30_e120", "p70_eq1620", "p70_e120"),
    ("qzo", "1620 steps (deployed)", "p30_e120", "p70_eq1620", "p70_e120"),
    ("eco", "1620 steps (deployed)", "p30_e120", "p70_eq1620", "p70_e120"),
]
REF_SWEEPS = {"S01": "exp6_acc_epo_revised/exp6{}/results/sweep.json",
              "S02": "exp11_acc_epo_S02/exp11{}/results/sweep.json",
              "S03": "exp12_acc_epo_S03/exp12{}/results/sweep.json",
              "S04": "exp13_acc_epo_S04/exp13{}/results/sweep.json"}
REF_SUFFIX = {"zo": "a_ZO", "qzo": "b_QZO", "eco": "c_QZO_ECO"}
# exp1_BP_simulation/results/fold3_vocalized.md (seed 42, 40 epochs): b2..b5 per subject
REF_BP40 = {"S01": [87.78, 76.11, 82.22, 83.89], "S02": [75.56, 72.22, 68.33, 68.89],
            "S03": [67.78, 70.00, 73.89, 75.56], "S04": [82.22, 85.56, 90.56, 86.67]}


def load(recipe, arm, subj):
    p = os.path.join(R, recipe, arm, f"{subj}.json")
    return json.load(open(p)) if os.path.exists(p) else None


def reference(recipe, arm, subj):
    if recipe == "bp" and arm == "p30_e40":
        return REF_BP40[subj]
    if recipe in REF_SUFFIX and arm == "p30_e120":
        d = json.load(open(os.path.join(CLEANUP, REF_SWEEPS[subj].format(REF_SUFFIX[recipe]))))
        e = d["sweep"]["120"]
        return [e[str(r)]["val_next"] for r in (1, 2, 3, 4)]
    return None


def main():
    rows, md = [], ["# exp21d results (auto-generated by analyze.py)\n"]
    table = {}
    for recipe in NAMES:
        for arm in ARM_INFO:
            for s in SUBJ:
                d = load(recipe, arm, s)
                if d is None:
                    continue
                pr = d["per_round"]
                nx = [pr[str(r)]["val_next"] for r in (1, 2, 3, 4)]
                vi = [pr[str(r)]["val_in"] for r in (1, 2, 3, 4)]
                table[(recipe, arm, s)] = (nx, vi, d)
                for r in (1, 2, 3, 4):
                    rows.append({"recipe": recipe, "arm": arm, "subject": s, "round": r,
                                 "val_next": pr[str(r)]["val_next"], "val_in": pr[str(r)]["val_in"],
                                 "train": pr[str(r)]["train"],
                                 "update_steps": pr[str(r)]["update_steps"],
                                 "train_forwards": pr[str(r)]["train_forwards"],
                                 "moved_step_fraction": pr[str(r)].get("moved_step_fraction", "")})
    with open(os.path.join(R, "summary.csv"), "w", newline="") as h:
        w = csv.DictWriter(h, fieldnames=list(rows[0].keys()))
        w.writeheader(); w.writerows(rows)

    # --- reproduction check of the 30 % baselines
    md.append("## Reproduction check (30 % baselines vs earlier runs of the same setting)\n")
    md.append("| recipe | arm | subject | this run (r1..r4 val_next) | earlier run | max abs diff |")
    md.append("|---|---|---|---|---|---:|")
    for (recipe, arm, s), (nx, _, _) in sorted(table.items()):
        ref = reference(recipe, arm, s)
        if ref is None:
            continue
        diff = max(abs(a - b) for a, b in zip(nx, ref))
        md.append(f"| {recipe} | {arm} | {s} | {', '.join(f'{v:.2f}' for v in nx)} | "
                  f"{', '.join(f'{v:.2f}' for v in ref)} | {diff:.2f} |")
    md.append("")

    # --- per comparison tables
    summary = []
    for recipe, budget, base, eq, more in COMPARISONS:
        arms = [a for a in (base, eq, more) if a]
        if not all((recipe, a, s) in table for a in (base, eq) for s in SUBJ):
            md.append(f"## {NAMES[recipe]} @ {budget}: INCOMPLETE\n")
            continue
        md.append(f"## {NAMES[recipe]} — {budget}\n")
        md.append("| arm | data | epochs | steps/round | fwd/round | subject | r1 | r2 | r3 | r4 | "
                  "**mean val_next** | mean val_in |")
        md.append("|---|---|---|---:|---:|---|---:|---:|---:|---:|---:|---:|")
        means = {}
        for a in arms:
            if not all((recipe, a, s) in table for s in SUBJ):
                continue
            subj_means = []
            for s in SUBJ:
                nx, vi, d = table[(recipe, a, s)]
                pct, nwin, ep = ARM_INFO[a]
                subj_means.append((np.mean(nx), np.mean(vi)))
                md.append(f"| {a} | {pct} ({nwin}) | {ep} | {d['update_steps_per_round'][0]} | "
                          f"{d['train_forwards_per_round'][0]} | {s} | "
                          + " | ".join(f"{v:.2f}" for v in nx)
                          + f" | **{np.mean(nx):.2f}** | {np.mean(vi):.2f} |")
            m_next = float(np.mean([m[0] for m in subj_means]))
            m_in = float(np.mean([m[1] for m in subj_means]))
            means[a] = (m_next, m_in, [m[0] for m in subj_means])
            md.append(f"| **{a}** | | | | | **mean** | | | | | **{m_next:.2f}** | {m_in:.2f} |")
        d_eq = [e - b for e, b in zip(means[eq][2], means[base][2])]
        md.append("")
        md.append(f"Delta 70 % equal-steps − 30 %: per subject "
                  + ", ".join(f"{s} {v:+.2f}" for s, v in zip(SUBJ, d_eq))
                  + f"; **mean {means[eq][0] - means[base][0]:+.2f} pp** (val_in "
                  f"{means[eq][1] - means[base][1]:+.2f}).")
        if more and more in means:
            md.append(f"Delta 70 % more-steps − 30 %: **{means[more][0] - means[base][0]:+.2f} pp** "
                      f"(higher latency).")
        md.append("")
        summary.append((recipe, budget, base, eq, more, means))
    with open(os.path.join(R, "summary.md"), "w") as h:
        h.write("\n".join(md) + "\n")
    with open(os.path.join(R, "summary.json"), "w") as h:
        json.dump([{"recipe": r, "budget": b, "baseline": ba, "equal_steps": e, "more_steps": mo,
                    "means": {k: {"val_next": v[0], "val_in": v[1], "per_subject": dict(zip(SUBJ, v[2]))}
                              for k, v in m.items()}} for r, b, ba, e, mo, m in summary], h, indent=1)
    print("\n".join(md))
    plot(summary)


def plot(summary):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    C_BASE, C_EQ, C_MORE = "#2a78d6", "#eb6834", "#8a8984"
    n = len(summary)
    fig, axes = plt.subplots(1, n, figsize=(3.4 * n, 4.2), sharey=True)
    axes = np.atleast_1d(axes)
    xs = np.arange(len(SUBJ) + 1)
    labels = SUBJ + ["Mean"]
    for ax, (recipe, budget, base, eq, more, means) in zip(axes, summary):
        def vals(a):
            return means[a][2] + [means[a][0]]
        for x in xs:
            ax.plot([x, x], [vals(base)[x], vals(eq)[x]], color="#c3c2b7", lw=2, zorder=1)
        ax.scatter(xs, vals(base), s=55, color=C_BASE, zorder=3, edgecolor="white", linewidth=1.5,
                   label=f"30 % ({base})")
        ax.scatter(xs, vals(eq), s=55, color=C_EQ, marker="D", zorder=3, edgecolor="white",
                   linewidth=1.5, label=f"70 % equal steps ({eq})")
        if more and more in means:
            ax.scatter(xs, vals(more), s=40, facecolor="none", edgecolor=C_MORE, marker="o",
                       linewidth=1.5, zorder=2, label=f"70 % more steps ({more}, higher latency)")
        dm = means[eq][0] - means[base][0]
        ax.axvline(len(SUBJ) - 0.5, color="#e6e5e0", lw=1)
        ax.set_xticks(xs, labels)
        ax.set_title(f"{NAMES[recipe]}\n{budget.split(' (')[0]}/round  ·  Δmean {dm:+.2f} pp", fontsize=10)
        ax.grid(axis="y", color="#eeeeec", lw=0.8)
        ax.set_axisbelow(True)
        for sp in ("top", "right"):
            ax.spines[sp].set_visible(False)
    axes[0].set_ylabel("balanced acc. on next batch, mean of 4 rounds (%)")
    fig.suptitle("exp21d — 30 % vs 70 % fine-tuning data at equal update steps "
                 "(fold 3, vocalized, seed 42)", fontsize=11)
    from matplotlib.lines import Line2D
    handles = [Line2D([], [], marker="o", ls="", color=C_BASE, markersize=8, label="30 % data (54 windows), baseline"),
               Line2D([], [], marker="D", ls="", color=C_EQ, markersize=7, label="70 % data (126 windows), SAME update steps"),
               Line2D([], [], marker="o", ls="", markerfacecolor="none", markeredgecolor=C_MORE,
                      markersize=7, label="70 % data, same epochs = 2.33x steps (higher latency)")]
    fig.legend(handles=handles, loc="lower center", ncol=3, frameon=False, fontsize=9)
    fig.tight_layout(rect=(0, 0.07, 1, 1))
    out = os.path.join(R, "exp21d_70pct_equal_steps.png")
    fig.savefig(out, dpi=150)
    print("wrote", out)


if __name__ == "__main__":
    main()
